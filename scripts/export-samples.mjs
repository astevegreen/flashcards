#!/usr/bin/env node
/**
 * Regenerates `content/samples/` (§10.1) from the built-in sample decks in
 * `packages/core/src/samples/decks.ts`, so file-based samples never drift from the
 * in-app ones. Each sample deck becomes a folder the CLI can build directly:
 *
 *   content/samples/<deck-slug>/flashpkg.config.json   name, language, note_type_id
 *   content/samples/<deck-slug>/<Deck Name>.csv         header row = note type field labels
 *   content/samples/<deck-slug>/pages/<slug>.md         lesson pages linked to that deck
 *
 *   node scripts/export-samples.mjs
 *   pnpm --filter @flash/cli exec flash-cli build content/samples/sample-ko-vocab
 *
 * Requires Node 24+ (runs the TypeScript core directly via type stripping).
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildSampleDeckEvents,
  createEventFactory,
  createHlcState,
  FLASH_NAMESPACE_UUID,
  replayAllEvents,
  uuidv5,
} from '../packages/core/src/index.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'content', 'samples');
const SEED_MS = Date.UTC(2026, 0, 1);

const state = replayAllEvents(
  buildSampleDeckEvents(
    createEventFactory('samples', 0, createHlcState('samples', SEED_MS)),
    SEED_MS,
  ),
);

/** RFC 4180 field quoting. */
function csvField(value) {
  const s = String(value ?? '');
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function safeName(name) {
  return name.replace(/[<>:"/\\|?*]+/g, '-').trim() || 'deck';
}

rmSync(outRoot, { recursive: true, force: true });
mkdirSync(outRoot, { recursive: true });

// Course items tell us which deck each lesson page belongs with.
const pagesByDeckId = new Map();
for (const course of state.courses.values()) {
  const pageIds = course.items.filter((i) => i.kind === 'page').map((i) => i.ref_id);
  for (const item of course.items) {
    if (item.kind !== 'deck') continue;
    const list = pagesByDeckId.get(item.ref_id) ?? [];
    list.push(...pageIds);
    pagesByDeckId.set(item.ref_id, list);
  }
}

const index = [];
const decks = [...state.decks.values()].sort((a, b) => a.name.localeCompare(b.name));
for (const deck of decks) {
  const noteType = state.noteTypes.get(deck.note_type_id);
  if (!noteType) continue;
  const slug =
    [
      'sample-ko-vocab',
      'sample-ja-vocab',
      'sample-ja-cloze',
      'sample-zh-vocab',
      'sample-en-vocab',
    ].find((s) => uuidv5(FLASH_NAMESPACE_UUID, s) === deck.id) ?? `deck-${deck.id.slice(0, 8)}`;
  const dir = join(outRoot, slug);
  mkdirSync(dir, { recursive: true });

  const notes = [...state.notes.values()]
    .filter((n) => n.deck_id === deck.id && !n.archived)
    .sort((a, b) => a.created_order - b.created_order);
  const fields = noteType.fields.filter((f) => f.kind !== 'image' && f.kind !== 'audio');
  const header = [...fields.map((f) => f.label), 'Tags', 'Card ID'];
  const rows = notes.map((n) => [
    ...fields.map((f) => n.fields[f.key] ?? ''),
    n.tags.join(';'),
    n.source_key,
  ]);
  const csv = [header, ...rows].map((r) => r.map(csvField).join(',')).join('\r\n') + '\r\n';
  const csvName = `${safeName(deck.name)}.csv`;
  writeFileSync(join(dir, csvName), csv, 'utf8');

  writeFileSync(
    join(dir, 'flashpkg.config.json'),
    JSON.stringify(
      {
        name: deck.name,
        package_id: `pkg:${slug}`,
        version: '1.0.0',
        language: deck.language,
        note_type_id: deck.note_type_id,
      },
      null,
      2,
    ) + '\n',
    'utf8',
  );

  const pageIds = [...new Set(pagesByDeckId.get(deck.id) ?? [])];
  for (const pageId of pageIds) {
    const page = state.pages.get(pageId);
    if (!page) continue;
    mkdirSync(join(dir, 'pages'), { recursive: true });
    const frontmatter = [
      '---',
      `slug: ${JSON.stringify(page.slug)}`,
      `title: ${JSON.stringify(page.title)}`,
      ...(page.lang ? [`lang: ${JSON.stringify(page.lang)}`] : []),
      ...(page.tags.length
        ? [`tags: [${page.tags.map((t) => JSON.stringify(t)).join(', ')}]`]
        : []),
      '---',
      '',
    ].join('\n');
    writeFileSync(
      join(dir, 'pages', `${page.slug}.md`),
      frontmatter + page.markdown.trimEnd() + '\n',
      'utf8',
    );
  }

  index.push({ slug, name: deck.name, language: deck.language, notes: notes.length, csv: csvName });
}

const readme = [
  '# Sample content',
  '',
  'Generated by `node scripts/export-samples.mjs` from the built-in sample decks',
  '(`packages/core/src/samples/decks.ts`). Do not edit by hand; edit the source and regenerate.',
  '',
  'Each folder is a self-contained package the CLI can build:',
  '',
  '```sh',
  'pnpm --filter @flash/cli exec flash-cli build content/samples/sample-ko-vocab',
  '```',
  '',
  'CSV headers are the note type field labels plus `Tags` (`;`-separated) and `Card ID`, the',
  'same columns the in-app CSV import and Google Sheets sources read.',
  '',
  '| Folder | Deck | Language | Notes |',
  '|---|---|---|---|',
  ...index.map((d) => `| \`${d.slug}\` | ${d.name} | \`${d.language}\` | ${d.notes} |`),
  '',
].join('\n');
writeFileSync(join(outRoot, 'README.md'), readme, 'utf8');

console.log(`Wrote ${index.length} sample deck folders to ${outRoot}`);
